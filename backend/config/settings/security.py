import os
from decouple import config


# ═══════════════════════════════════════════════════════════════════════════════
# 🔑 المفتاح السري - Secret Key
# ═══════════════════════════════════════════════════════════════════════════════
# الوصف: مفتاح التشفير الرئيسي لـ Django
# الاستخدام: توقيع الجلسات، CSRF tokens، تشفير البيانات
# ⚠️ تحذير: يجب تغييره في الإنتاج وعدم مشاركته أبداً!
# التوليد: python -c "from django.core.management.utils import get_random_secret_key; print(get_random_secret_key())"
# القيم: سلسلة عشوائية طويلة (50+ حرف)
# التوصية: ✅ استخدم مفتاح فريد لكل بيئة
SECRET_KEY = config('SECRET_KEY', default='django-insecure-CHANGE-THIS-IN-PRODUCTION-IMMEDIATELY')


# ═══════════════════════════════════════════════════════════════════════════════
# 🐛 وضع التصحيح - Debug Mode
# ═══════════════════════════════════════════════════════════════════════════════
# الوصف: يفعّل رسائل الخطأ التفصيلية وأدوات التصحيح
# ⚠️ تحذير: يجب أن يكون False في الإنتاج!
# القيم: True (تطوير) | False (إنتاج)
# المخاطر: كشف معلومات حساسة، مسارات الملفات، إعدادات قاعدة البيانات
# التوصية: ✅ False في الإنتاج، True في التطوير فقط
DEBUG = config('DEBUG', default=False, cast=bool)


# ═══════════════════════════════════════════════════════════════════════════════
# 🌐 المضيفين المسموح بهم - Allowed Hosts
# ═══════════════════════════════════════════════════════════════════════════════
# الوصف: قائمة النطاقات/IPs المسموح لها بالوصول للتطبيق
# الاستخدام: حماية من هجمات Host header poisoning
# القيم: قائمة نطاقات (مثل: 'example.com', '192.168.1.1')
# التوصية: ✅ حدد النطاقات بدقة، لا تستخدم '*' في الإنتاج
ALLOWED_HOSTS_STR = config('ALLOWED_HOSTS', default='localhost,127.0.0.1')
ALLOWED_HOSTS = [host.strip() for host in ALLOWED_HOSTS_STR.split(',') if host.strip()]


# ═══════════════════════════════════════════════════════════════════════════════
# 🔒 حماية CSRF - Cross-Site Request Forgery Protection
# ═══════════════════════════════════════════════════════════════════════════════

# ─────────────────────────────────────────────────────────────────────────────
# CSRF_TRUSTED_ORIGINS
# ─────────────────────────────────────────────────────────────────────────────
# الوصف: قائمة المصادر الموثوقة لطلبات CSRF
# الاستخدام: للسماح بطلبات من نطاقات أخرى (مثل frontend منفصل)
# القيم: قائمة URLs كاملة (مثل: 'https://frontend.example.com')
# التوصية: ✅ أضف فقط النطاقات الموثوقة
CSRF_TRUSTED_ORIGINS_STR = config('CSRF_TRUSTED_ORIGINS', default='http://localhost:8000,http://127.0.0.1:8000')
CSRF_TRUSTED_ORIGINS = [origin.strip() for origin in CSRF_TRUSTED_ORIGINS_STR.split(',') if origin.strip()]

# ─────────────────────────────────────────────────────────────────────────────
# CSRF_COOKIE_SECURE
# ─────────────────────────────────────────────────────────────────────────────
# الوصف: إرسال CSRF Cookie عبر HTTPS فقط
# القيم: True (إنتاج مع HTTPS) | False (تطوير محلي)
# المخاطر: إذا False في الإنتاج، يمكن سرقة الـ token عبر اتصال غير مشفر
# التوصية: ✅ True في الإنتاج
CSRF_COOKIE_SECURE = config('CSRF_COOKIE_SECURE', default=False, cast=bool)

# ─────────────────────────────────────────────────────────────────────────────
# CSRF_COOKIE_HTTPONLY
# ─────────────────────────────────────────────────────────────────────────────
# الوصف: منع JavaScript من الوصول لـ CSRF Cookie
# القيم: True | False
# ملاحظة: Django يحتاج الوصول من JS لبعض الحالات، لذا الافتراضي False
# التوصية: ⚠️ اتركه False إلا إذا كنت متأكداً
CSRF_COOKIE_HTTPONLY = False

# ─────────────────────────────────────────────────────────────────────────────
# CSRF_COOKIE_SAMESITE
# ─────────────────────────────────────────────────────────────────────────────
# الوصف: سياسة SameSite لـ CSRF Cookie
# القيم: 'Strict' | 'Lax' | 'None' | False
# - 'Strict': لا يُرسل مع أي طلب من موقع خارجي (أعلى حماية)
# - 'Lax': يُرسل مع طلبات GET من مواقع خارجية فقط (افتراضي)
# - 'None': يُرسل مع جميع الطلبات (يتطلب Secure=True)
# التوصية: ✅ 'Lax' للتوازن بين الأمان والتوافقية
CSRF_COOKIE_SAMESITE = 'Lax'

# ─────────────────────────────────────────────────────────────────────────────
# CSRF_COOKIE_NAME & CSRF_COOKIE_AGE
# ─────────────────────────────────────────────────────────────────────────────
CSRF_COOKIE_NAME = 'csrftoken'
CSRF_COOKIE_AGE = 60 * 60 * 24 * 7  # أسبوع واحد


# ═══════════════════════════════════════════════════════════════════════════════
# 🍪 إعدادات Session - Session Settings
# ═══════════════════════════════════════════════════════════════════════════════

# ─────────────────────────────────────────────────────────────────────────────
# SESSION_COOKIE_SECURE
# ─────────────────────────────────────────────────────────────────────────────
# الوصف: إرسال Session Cookie عبر HTTPS فقط
# القيم: True (إنتاج مع HTTPS) | False (تطوير محلي)
# المخاطر: إذا False في الإنتاج، يمكن اختطاف الجلسة عبر اتصال غير مشفر
# التوصية: ✅ True في الإنتاج
SESSION_COOKIE_SECURE = config('SESSION_COOKIE_SECURE', default=False, cast=bool)

# ─────────────────────────────────────────────────────────────────────────────
# SESSION_COOKIE_HTTPONLY
# ─────────────────────────────────────────────────────────────────────────────
# الوصف: منع JavaScript من الوصول للـ Session Cookie
# القيم: True | False
# المخاطر: إذا False، يمكن لـ XSS سرقة الجلسة
# التوصية: ✅ True دائماً
SESSION_COOKIE_HTTPONLY = True

# ─────────────────────────────────────────────────────────────────────────────
# SESSION_COOKIE_SAMESITE
# ─────────────────────────────────────────────────────────────────────────────
# الوصف: سياسة SameSite لـ Session Cookie
# القيم: 'Strict' | 'Lax' | 'None' | False
# - 'Strict': أعلى حماية، قد يسبب مشاكل في بعض السيناريوهات
# - 'Lax': توازن جيد (افتراضي)
# التوصية: ✅ 'Lax' أو 'Strict' حسب متطلباتك
SESSION_COOKIE_SAMESITE = 'Lax'

# ─────────────────────────────────────────────────────────────────────────────
# إعدادات إضافية للـ Session
# ─────────────────────────────────────────────────────────────────────────────
SESSION_COOKIE_NAME = 'sms_sessionid'
SESSION_COOKIE_AGE = config('SESSION_COOKIE_AGE', default=28800, cast=int)  # 8 ساعات (NIST AAL2)
SESSION_ENGINE = 'django.contrib.sessions.backends.db'
SESSION_EXPIRE_AT_BROWSER_CLOSE = False  # الجلسة تبقى بعد إغلاق المتصفح

# ─────────────────────────────────────────────────────────────────────────────
# BLACKLIST_ON_MISSING_SESSION (مخصص)
# ─────────────────────────────────────────────────────────────────────────────
# الوصف: إعداد مخصص من OpenSoftCoreV41
# الاستخدام: حظر الطلبات التي لا تحتوي على جلسة صالحة
# القيم: True | False
# التوصية: ⚠️ راجع استخدامه في المشروع
BLACKLIST_ON_MISSING_SESSION = config('BLACKLIST_ON_MISSING_SESSION', default=True, cast=bool)

# ─────────────────────────────────────────────────────────────────────────────
# INACTIVITY_TIMEOUT_SECONDS (مخصص)
# ─────────────────────────────────────────────────────────────────────────────
# الوصف: مدة الخمول المسموح بها قبل إنهاء الجلسة تلقائياً
# القيم: عدد صحيح (بالثواني) — الافتراضي: 1800 ثانية (30 دقيقة)
# التوصية: ✅ 1800 ثانية للإنتاج
INACTIVITY_TIMEOUT_SECONDS = config('INACTIVITY_TIMEOUT_SECONDS', default=1800, cast=int)


# ═══════════════════════════════════════════════════════════════════════════════
# 🔐 HTTPS و HSTS - HTTP Strict Transport Security
# ═══════════════════════════════════════════════════════════════════════════════

# ─────────────────────────────────────────────────────────────────────────────
# SECURE_SSL_REDIRECT
# ─────────────────────────────────────────────────────────────────────────────
# الوصف: إعادة توجيه جميع طلبات HTTP إلى HTTPS
# القيم: True (إنتاج) | False (تطوير)
# ملاحظة: تأكد من وجود شهادة SSL قبل التفعيل
# التوصية: ✅ True في الإنتاج
SECURE_SSL_REDIRECT = config('SECURE_SSL_REDIRECT', default=False, cast=bool)

# ─────────────────────────────────────────────────────────────────────────────
# SECURE_HSTS_SECONDS
# ─────────────────────────────────────────────────────────────────────────────
# الوصف: مدة تذكر المتصفح أن الموقع HTTPS فقط (بالثواني)
# القيم: 0 (معطل) | 31536000 (سنة - موصى به)
# المخاطر: إذا كان عالياً وأزلت HTTPS، المستخدمون لن يستطيعوا الوصول!
# التوصية: ✅ ابدأ بـ 3600 (ساعة) ثم زد تدريجياً إلى 31536000 (سنة)
SECURE_HSTS_SECONDS = config('SECURE_HSTS_SECONDS', default=31536000, cast=int)

# ─────────────────────────────────────────────────────────────────────────────
# SECURE_HSTS_INCLUDE_SUBDOMAINS
# ─────────────────────────────────────────────────────────────────────────────
# الوصف: تطبيق HSTS على جميع النطاقات الفرعية
# القيم: True | False
# ⚠️ تحذير: تأكد أن جميع النطاقات الفرعية تدعم HTTPS!
# التوصية: ✅ True إذا كانت جميع النطاقات الفرعية تدعم HTTPS
SECURE_HSTS_INCLUDE_SUBDOMAINS = config('SECURE_HSTS_INCLUDE_SUBDOMAINS', default=True, cast=bool)

# ─────────────────────────────────────────────────────────────────────────────
# SECURE_HSTS_PRELOAD
# ─────────────────────────────────────────────────────────────────────────────
# الوصف: إضافة الموقع لقائمة HSTS المحملة مسبقاً في المتصفحات
# الاستخدام: حماية من أول زيارة (قبل أن يتعلم المتصفح)
# القيم: True | False
# ⚠️ تحذير: بمجرد الإضافة للقائمة، صعب جداً الإزالة!
# الخطوات: 1) تأكد من صحة الإعدادات 2) قدم على hstspreload.org
# التوصية: ✅ True فقط بعد التأكد من استقرار HTTPS
SECURE_HSTS_PRELOAD = config('SECURE_HSTS_PRELOAD', default=False, cast=bool)


# ═══════════════════════════════════════════════════════════════════════════════
# 🛡️ رؤوس الأمان - Security Headers
# ═══════════════════════════════════════════════════════════════════════════════

# ─────────────────────────────────────────────────────────────────────────────
# SECURE_CONTENT_TYPE_NOSNIFF
# ─────────────────────────────────────────────────────────────────────────────
# الوصف: يضيف رأس X-Content-Type-Options: nosniff
# الاستخدام: منع المتصفح من تخمين نوع المحتوى (MIME sniffing)
# الحماية: منع هجمات تحويل ملفات النص لتنفيذ كود
# القيم: True | False
# التوصية: ✅ True دائماً
SECURE_CONTENT_TYPE_NOSNIFF = True

# ─────────────────────────────────────────────────────────────────────────────
# X_FRAME_OPTIONS
# ─────────────────────────────────────────────────────────────────────────────
# الوصف: رأس X-Frame-Options للحماية من Clickjacking
# القيم: 'DENY' | 'SAMEORIGIN' | 'ALLOW-FROM uri'
# - 'DENY': لا يُعرض في أي iframe (أعلى حماية)
# - 'SAMEORIGIN': يُعرض فقط في iframe من نفس النطاق
# الحماية: منع تضمين الموقع في مواقع خارجية لسرقة النقرات
# التوصية: ✅ 'DENY' أو 'SAMEORIGIN'
X_FRAME_OPTIONS = 'DENY'

# ─────────────────────────────────────────────────────────────────────────────
# SECURE_BROWSER_XSS_FILTER (مهمل - Deprecated)
# ─────────────────────────────────────────────────────────────────────────────
# الوصف: كان يفعّل فلتر XSS في المتصفحات القديمة
# الحالة: ❌ مهمل - أزيل من المتصفحات الحديثة
# السبب: كان يسبب ثغرات أمنية بدلاً من حمايتها!
# التوصية: ❌ لا تستخدمه - اعتمد على CSP بدلاً منه
# SECURE_BROWSER_XSS_FILTER = True  # لا تستخدم!

# ─────────────────────────────────────────────────────────────────────────────
# SECURE_REFERRER_POLICY
# ─────────────────────────────────────────────────────────────────────────────
# الوصف: يحدد كيفية إرسال Referrer header مع الطلبات
# القيم المتاحة:
# - 'no-referrer': لا يُرسل أبداً
# - 'no-referrer-when-downgrade': لا يُرسل عند الانتقال من HTTPS لـ HTTP
# - 'same-origin': يُرسل فقط لنفس النطاق
# - 'origin': يُرسل النطاق فقط (بدون المسار)
# - 'strict-origin': مثل origin لكن لا يُرسل عند downgrade
# - 'origin-when-cross-origin': المسار الكامل لنفس النطاق، النطاق فقط لغيره
# - 'strict-origin-when-cross-origin': الأكثر توازناً (موصى به)
# - 'unsafe-url': يُرسل دائماً (غير آمن!)
# التوصية: ✅ 'strict-origin-when-cross-origin'
SECURE_REFERRER_POLICY = 'strict-origin-when-cross-origin'


# ═══════════════════════════════════════════════════════════════════════════════
# 🌍 Cross-Origin Policies (COOP, COEP, CORP)
# ═══════════════════════════════════════════════════════════════════════════════

# ─────────────────────────────────────────────────────────────────────────────
# SECURE_CROSS_ORIGIN_OPENER_POLICY
# ─────────────────────────────────────────────────────────────────────────────
# الوصف: رأس Cross-Origin-Opener-Policy
# الاستخدام: عزل النافذة عن السياقات الخارجية
# الحماية: منع هجمات Spectre و side-channel attacks
# القيم: 'same-origin' | 'same-origin-allow-popups' | 'unsafe-none'
# - 'same-origin': عزل كامل (أعلى حماية، قد يؤثر على popups)
# - 'same-origin-allow-popups': يسمح بـ popups من نفس النطاق
# التوصية: ✅ 'same-origin' إذا لم تستخدم popups خارجية
SECURE_CROSS_ORIGIN_OPENER_POLICY = 'same-origin'


# ═══════════════════════════════════════════════════════════════════════════════
# 🔐 Proxy Settings (لـ Load Balancer/Reverse Proxy)
# ═══════════════════════════════════════════════════════════════════════════════

# ─────────────────────────────────────────────────────────────────────────────
# SECURE_PROXY_SSL_HEADER
# ─────────────────────────────────────────────────────────────────────────────
# الوصف: يخبر Django أن الطلب جاء عبر HTTPS من الـ proxy
# الاستخدام: عند استخدام Load Balancer مثل Nginx أو AWS ELB
# القيم: tuple مثل ('HTTP_X_FORWARDED_PROTO', 'https')
# ⚠️ تحذير: تأكد أن الـ proxy يضبط هذا الـ header بشكل صحيح!
# التوصية: ✅ فعّله فقط إذا كنت خلف proxy موثوق
USE_PROXY_SSL = config('USE_PROXY_SSL', default=False, cast=bool)
if USE_PROXY_SSL:
    SECURE_PROXY_SSL_HEADER = ('HTTP_X_FORWARDED_PROTO', 'https')


